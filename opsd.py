def check_args(args: argparse.Namespace) -> None:
    args.benchmarks = [b.strip() for b in args.benchmarks.split(",") if b.strip()]
    unknown = [b for b in args.benchmarks if b not in data.BENCHMARKS]
    if unknown:
        raise SystemExit(f"unknown benchmarks: {unknown}")
    if args.n_gpus % args.tp:
        raise SystemExit("--n-gpus must be a multiple of --tp")


def claim_output(out: Path, label: str) -> bool:
    """False if `out` holds a finished run. Otherwise create `out` empty and return True.

    Training cannot resume mid-run, so an interrupted run starts over; its files are moved aside.
    """
    if (out / "done.json").exists():
        print(f"[{label}] {out} is complete", flush=True)
        return False
    if out.exists() and any(out.iterdir()):
        previous = out.parent / f"{out.name}.incomplete-{time.strftime('%Y%m%d-%H%M%S')}"
        shutil.move(str(out), previous)
        print(f"[{label}] moved the interrupted run to {previous}", flush=True)
    out.mkdir(parents=True, exist_ok=True)
    return True


def mark_done(out: Path) -> None:
    (out / "done.json").write_text(json.dumps({"finished": time.strftime("%Y-%m-%dT%H:%M:%S%z")}) + "\n")


def run(args: argparse.Namespace, method: str) -> None:
    """Train with `method` ("opsd", "lockstep", or "rft") unless `args.out` already holds a finished run."""
    data.load_dotenv_if_present()
    check_args(args)
    out = Path(args.out)
    if not claim_output(out, method):
        return
    trainer = Hindsight(args, method)
    config = {"method": method, **vars(args), "model_path": trainer.model_path,
              "revision": args.revision or MODELS.get(args.model), "train_temperature": TRAIN_TEMPERATURE,
              "eval_temperature": EVAL_TEMPERATURE, "top_p": TOP_P,
              "data_pins": json.loads((Path(args.data) / "manifest.json").read_text())["pins"]}
    (out / "config.json").write_text(json.dumps(config, indent=2) + "\n")
    trainer.start()
    if method == "lockstep":
        trainer.run_lockstep()
    else:
        trainer.run()
    mark_done(out)


def main(argv: list[str] | None = None) -> None:
    args = parse_args(argv)
    run(args, "lockstep" if args.lockstep else "opsd")


