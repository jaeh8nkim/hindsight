def find(ids: list[int], sub: list[int]) -> int:
    """Index of the first occurrence of `sub` in `ids`, or -1."""
    n = len(sub)
    for i in range(len(ids) - n + 1):
        if ids[i:i + n] == sub:
            return i
    return -1


def snap_back(ids: list[int], target: int, decode: Callable[[list[int]], str], lookback: int = 200) -> int:
    """The last token boundary at or before the last sentence end within `lookback` tokens of `target`."""
    start = max(0, target - lookback)
    window = decode(ids[start:target])
    found = [window.rfind(m) + len(m) for m in SENTENCE_ENDS if window.rfind(m) >= 0]
    if not found:
        return target
    cut = max(found)
    for end in range(target, start, -1):
        if len(decode(ids[start:end])) <= cut:
            return end
    return start


def reinjection_positions(ids: list[int], close_ids: list[int], interval: int,
                          decode: Callable[[list[int]], str]) -> list[int]:
    """Rollout positions before which the teacher re-reads its context, all inside the thinking block."""
    close = find(ids, close_ids)
    end = len(ids) if close < 0 else close + len(close_ids)
    positions = []
    for target in range(interval, min(len(ids), end), interval):
        position = snap_back(ids, target, decode)
        if 0 < position < end and position not in positions:
            positions.append(position)
    return sorted(positions)


def interleave(ids: list[int], positions: list[int], snippet: list[int]) -> tuple[list[int], list[int]]:
    """The teacher's copy of a rollout and its mask: 1 at rollout tokens, 0 at inserted snippets."""
    marks = set(positions)
    tokens, mask = [], []
    for t, token in enumerate(ids):
        if t in marks:
            tokens += snippet
            mask += [0] * len(snippet)
        tokens.append(token)
        mask.append(1)
    return tokens, mask


def token_losses(kind: str, student: torch.Tensor, teacher: torch.Tensor | None = None,
                 targets: torch.Tensor | None = None, beta: float = JSD_BETA) -> torch.Tensor:
    """Per-token loss from student logits (and teacher logits or targets), in float32."""
    s = F.log_softmax(student.float(), dim=-1)
    if kind == "ce":
        return F.nll_loss(s, targets, reduction="none")
    t = F.log_softmax(teacher.float(), dim=-1)
    if kind == "reverse_kl":
        return (s.exp() * (s - t)).sum(-1)
    if kind == "forward_kl":
        return (t.exp() * (t - s)).sum(-1)
    if kind == "jsd":
        m = torch.logaddexp(t + math.log(beta), s + math.log(1.0 - beta))
        return beta * (t.exp() * (t - m)).sum(-1) + (1.0 - beta) * (s.exp() * (s - m)).sum(-1)
    raise ValueError(f"unknown loss {kind}")


def backward_in_chunks(student: torch.Tensor, teacher: torch.Tensor | None, targets: torch.Tensor,
                       kind: str, coef: float, chunk: int = 1024) -> float:
    """Backpropagate coef * sum of per-token losses chunk by chunk; return the unscaled sum."""
    leaf = student.detach().requires_grad_(True)
    total = 0.0
    for a in range(0, leaf.shape[0], chunk):
        b = a + chunk
        part = token_losses(kind, leaf[a:b], None if teacher is None else teacher[a:b], targets[a:b]).sum()
        (part * coef).backward()
        total += float(part.detach())
    student.backward(leaf.grad)
    return total


def response_logits(module, ids: torch.Tensor, keep: torch.Tensor) -> torch.Tensor:
    """Logits at positions `keep` of one unpadded sequence (each predicts the following token)."""
    positions = torch.arange(ids.numel(), device=ids.device).unsqueeze(0)
    with torch.autocast(device_type=get_device_name(), dtype=torch.bfloat16):
        output = module(input_ids=ids.unsqueeze(0), position_ids=positions, use_cache=False, logits_to_keep=keep)
    return output.logits[0]


def shortest_half(indices: list[int], lengths: list[int]) -> list[int]:
    if not indices:
        return []
    return sorted(sorted(indices, key=lambda i: (lengths[i], i))[: max(1, len(indices) // 2)])


