def load_rows(path: Path) -> list[dict]:
    import pandas as pd

    rows = []
    for record in pd.read_parquet(path).to_dict("records"):
        extra = {k: (v.tolist() if hasattr(v, "tolist") else v) for k, v in dict(record["extra_info"]).items()}
        rows.append({"index": int(extra["index"]), "problem": extra["problem"], "answer": str(extra["ground_truth"]),
                     "data_source": record["data_source"], "extra_info": extra})
    return rows


def resolve_model(model: str, revision: str | None) -> str:
    if Path(model).is_dir():
        return str(Path(model).resolve())
    from huggingface_hub import snapshot_download

    revision = revision or MODELS.get(model)
    if not revision:
        raise SystemExit(f"--revision is required for {model}")
    return snapshot_download(model, revision=revision,
                             allow_patterns=["*.json", "*.safetensors", "*.txt", "*.model", "*.jinja"])


def stop_token_ids(model_path: str, tokenizer) -> set[int]:
    ids = {tokenizer.eos_token_id}
    config = Path(model_path) / "generation_config.json"
    if config.exists():
        eos = json.loads(config.read_text()).get("eos_token_id")
        ids.update(eos if isinstance(eos, list) else [eos] if eos is not None else [])
    return ids


def verl_config(overrides: list[str]):
    import verl
    from hydra import compose, initialize_config_dir

    config_dir = Path(verl.__file__).resolve().parent / "trainer" / "config"
    with initialize_config_dir(config_dir=str(config_dir), version_base=None):
        return compose(config_name="ppo_trainer", overrides=overrides)


