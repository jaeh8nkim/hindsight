def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_common_args(parser, steps=100, batch_size=32)
    parser.add_argument("--context", choices=CONTEXTS, default="reflection_from_gt")
    parser.add_argument("--gating", choices=("all", "correct", "incorrect"), default="all")
    parser.add_argument("--loss", choices=("reverse_kl", "forward_kl", "jsd", "split"), default="reverse_kl")
    parser.add_argument("--reinjection", action="store_true")
    parser.add_argument("--reinjection-interval", type=int, default=2048)
    parser.add_argument("--reflection-tokens", type=int, default=6144)
    parser.add_argument("--continuation-tokens", type=int, default=2048)
    parser.add_argument("--lockstep", action="store_true", help="Prompt-matched correct-only / incorrect-only branches")
