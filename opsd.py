def outcome(correct: bool, finished: bool) -> str:
    return "correct" if correct else ("incorrect" if finished else "truncated")


def reflection_request(context: str, correct: bool, ground_truth: str, demo: str | None = None) -> str:
    template = REFLECTION[context]["correct" if correct else "incorrect"]
    text = template.replace("{ground_truth}", str(ground_truth))
    if "{expert_demonstration}" in text:
        if demo is None:
            raise ValueError(f"context {context} needs an expert demonstration")
        text = text.replace("{expert_demonstration}", demo)
    return text


def teacher_request(context: str, problem: str, memo: str | None) -> str:
    if context == "conciseness":
        return CONCISE + problem + data.REMEMBER
    prefix, suffix = RESOLVE if context == "resolve_from_demo" else RECALL
    return data.student_prompt(problem) + prefix + memo + suffix


def reinjection_snippet(context: str, memo: str | None) -> str | None:
    if context == "conciseness":
        return CONCISE_SNIPPET
    return RECALL_SNIPPET.replace("{context}", memo) if memo else None


def memo_of(text: str) -> str:
    """The reflection without its thinking: the text after the last </think>."""
    end = text.rfind("</think>")
    return (text[end + len("</think>"):] if end >= 0 else text).strip()


