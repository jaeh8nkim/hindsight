@dataclass
class Rollout:
    prompt: list[int]
    ids: list[int]
    finished: bool  # ended with a stop token; False when the token budget cut it off
    text: str
    correct: bool = False
    prediction: str = ""


def write_jsonl(path: Path, record: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(record, ensure_ascii=False) + "\n")


def mean(values: list[float]) -> float:
    return sum(values) / len(values) if values else 0.0


class Hindsight:
    """Drives generation (sglang servers), reflection, updates (FSDP workers), and evaluation."""

    def __init__(self, args: argparse.Namespace, method: str):
        from transformers import AutoTokenizer

        self.args, self.method = args, method
        self.out = Path(args.out)
        self.model_path = resolve_model(args.model, args.revision)
        self.tokenizer = AutoTokenizer.from_pretrained(self.model_path)
        self.stop_ids = stop_token_ids(self.model_path, self.tokenizer)
        self.close_ids = self.tokenizer.encode("</think>", add_special_tokens=False)
        self.force_close_ids = self.tokenizer.encode("\n</think>\n", add_special_tokens=False)
        data_dir = Path(args.data)
        self.train = load_rows(data_dir / "train.parquet")
        self.benchmarks = {name: load_rows(data_dir / f"val_{name}.parquet") for name in args.benchmarks}
        self.demos = None
        if getattr(args, "context", None) in DEMO_CONTEXTS:
            import pandas as pd

            path = data_dir / "expert_demos.parquet"
            if not path.exists():
                raise SystemExit(f"{path} is missing; generate it with `python data.py demos --out {data_dir}`")
            self.demos = {int(r["index"]): r["expert_demonstration"] for r in pd.read_parquet(path).to_dict("records")}
            missing = [row["index"] for row in self.train if row["index"] not in self.demos]
            if missing:
                raise SystemExit(f"{path} lacks demonstrations for {len(missing)} training prompts")
        self.active = None  # the branch snapshot currently loaded (lockstep)

    # -- workers -------------------------------------------------------------

    def start(self) -> None:
        import ray
        from verl.experimental.agent_loop import AgentLoopManager
        from verl.single_controller.ray import RayClassWithInitArgs, RayWorkerGroup
        from verl.single_controller.ray.base import create_colocated_worker_cls
        from verl.trainer.ppo.ray_trainer import ResourcePoolManager, Role

        config = training_config(self.args, self.model_path)
        init_ray()
        kind = Role.ActorRollout if self.method == "rft" else Role.ActorRolloutRef  # RFT needs no teacher
        role = str(kind)
        pools = ResourcePoolManager(resource_pool_spec={"global_pool": [self.args.n_gpus]},
                                    mapping={kind: "global_pool"})
        pools.create_resource_pool()
        worker = RayClassWithInitArgs(cls=ray.remote(HindsightWorker), config=config.actor_rollout_ref, role=role)
        group = RayWorkerGroup(resource_pool=pools.get_resource_pool(kind),
                               ray_cls_with_init=create_colocated_worker_cls(class_dict={role: worker}),
                               device_name=get_device_name())
        self.workers = group.spawn(prefix_set={role})[role]
        self.workers.init_model()
        self.rollout = AgentLoopManager(config=config, worker_group=self.workers, rm_resource_pool=None)
        self.servers = list(self.rollout.server_handles)

    @contextlib.contextmanager
    def engine(self):
        """Inference servers awake, holding the current actor weights."""
        self.rollout.wake_up()
        try:
            yield
        finally:
            self.rollout.sleep()

    def generate(self, prompts: list[list[int]], max_new_tokens: int, temperature: float,
                 on_result: Callable[[int, list[int]], Any] | None = None) -> list[Any]:
        """Sampled token ids for each prompt (inside `engine()`), exactly as the server returned them."""
        import ray

        params = {"temperature": temperature, "top_p": TOP_P, "repetition_penalty": 1.0,
                  "max_new_tokens": max_new_tokens}
        refs = [self.servers[i % len(self.servers)].generate.remote(
                    prompt_ids=prompt, sampling_params=params, request_id=uuid.uuid4().hex)
                for i, prompt in enumerate(prompts)]
        where = {ref: i for i, ref in enumerate(refs)}
        results: list[Any] = [None] * len(refs)
        pending = refs
        unterminated = 0
        while pending:
            done, pending = ray.wait(pending, num_returns=len(pending), timeout=5.0)
            for ref in done:
                ids = list(ray.get(ref).token_ids)
                unterminated += len(ids) < max_new_tokens and not self.finished(ids)
                results[where[ref]] = on_result(where[ref], ids) if on_result else ids
        if unterminated:  # the server should return the stop token; such responses count as cut off
            print(f"[warn] {unterminated} responses stopped before the token budget without a stop token", flush=True)
        return results

    def chat(self, messages: list[dict]) -> list[int]:
        return list(self.tokenizer.apply_chat_template(messages, add_generation_prompt=True, tokenize=True))

    def student_prompt(self, row: dict) -> list[int]:
        return self.chat([{"role": "user", "content": data.student_prompt(row["problem"])}])

    def decode(self, ids: list[int]) -> str:
        return self.tokenizer.decode(ids, skip_special_tokens=True)

    def finished(self, ids: list[int]) -> bool:
        return bool(ids) and ids[-1] in self.stop_ids

    def sample(self, rows: list[dict], per_prompt: int = 1) -> list[Rollout]:
        prompts = [self.student_prompt(row) for row in rows for _ in range(per_prompt)]
        outputs = self.generate(prompts, self.args.max_new_tokens, TRAIN_TEMPERATURE)
        rollouts = []
        for k, (prompt, ids) in enumerate(zip(prompts, outputs)):
            row = rows[k // per_prompt]
            rollout = Rollout(prompt, ids, self.finished(ids), self.decode(ids))
            rollout.correct, rollout.prediction = data.check_answer(
                rollout.text, row["answer"], row["data_source"], row["extra_info"])
            rollouts.append(rollout)
        return rollouts

    # -- branch snapshots (lockstep) -----------------------------------------

    def save_branch(self, name: str) -> None:
        for rank in range(self.args.n_gpus):  # one rank at a time bounds host memory
            self.workers.save_branch(str(self.out / "branches" / name), rank)
        self.active = name

    def activate(self, name: str) -> None:
        if self.active != name:
            for rank in range(self.args.n_gpus):
                self.workers.load_branch(str(self.out / "branches" / name), rank)
            self.active = name

    # -- distillation --------------------------------------------------------

    def reflect(self, rows: list[dict], rollouts: list[Rollout]) -> list[dict]:
        """The student's reflection on each rollout (inside `engine()`)."""
        requests, messages = [], []
        for row, rollout in zip(rows, rollouts):
            demo = self.demos[row["index"]] if self.demos else None
            message = reflection_request(self.args.context, rollout.correct, row["answer"], demo)
            messages.append(message)
            requests.append(self.chat([
                {"role": "user", "content": data.student_prompt(row["problem"])},
                {"role": "assistant", "content": rollout.text},
                {"role": "user", "content": message},
            ]))
        first = self.generate(requests, self.args.reflection_tokens, TRAIN_TEMPERATURE)
        cut = [j for j, ids in enumerate(first) if not self.finished(ids)]
        bridge = {j: [] if find(first[j], self.close_ids) >= 0 else self.force_close_ids for j in cut}
        more = self.generate([requests[j] + first[j] + bridge[j] for j in cut], self.args.continuation_tokens,
                             TRAIN_TEMPERATURE) if cut else []
        more = dict(zip(cut, more))
        reflections = []
        for j, ids in enumerate(first):
            full = ids + bridge.get(j, []) + more.get(j, [])
            reflections.append({"request": messages[j], "memo": memo_of(self.decode(full)), "tokens": len(full),
                                "continued": j in more, "finished": self.finished(full)})
        return reflections

    def distill_row(self, row: dict, rollout: Rollout, memo: str | None) -> dict:
        teacher_prompt = self.chat([{"role": "user", "content": teacher_request(self.args.context, row["problem"], memo)}])
        positions, snippet = [], []
        text = reinjection_snippet(self.args.context, memo) if self.args.reinjection else None
        if text:
            snippet = self.tokenizer.encode(text, add_special_tokens=False)
            positions = reinjection_positions(rollout.ids, self.close_ids, self.args.reinjection_interval,
                                              lambda ids: self.tokenizer.decode(ids, skip_special_tokens=False))
        body, mask = interleave(rollout.ids, positions, snippet)
        return {"student": rollout.prompt + rollout.ids, "prompt_len": len(rollout.prompt),
                "teacher": teacher_prompt + body, "teacher_mask": [0] * len(teacher_prompt) + mask,
                "reverse": rollout.correct, "reinjections": len(positions)}

    def update(self, rows: list[dict], loss: str) -> dict:
        """One optimizer step on `rows`; rows are balanced by length over ranks, padding rows weigh 0."""
        if not rows:
            return {"trained_rows": 0}
        world = self.args.n_gpus
        total = len(rows) + (-len(rows)) % world
        per_rank = total // world
        eos = self.tokenizer.eos_token_id
        slots: list[dict] = [{"student": [eos, eos], "prompt_len": 1, "teacher": [eos, eos], "teacher_mask": [0, 1],
                              "reverse": True, "weight": 0.0}] * total
        by_length = sorted(range(len(rows)), key=lambda i: -(len(rows[i]["student"]) + len(rows[i].get("teacher", ()))))
        for k, i in enumerate(by_length):
            slots[(k % world) * per_rank + k // world] = rows[i]

        def padded(key: str, dtype=torch.long) -> torch.Tensor:
            seqs = [slot[key] for slot in slots]
            out = torch.zeros(len(seqs), max(map(len, seqs)), dtype=dtype)
            for i, seq in enumerate(seqs):
                out[i, :len(seq)] = torch.tensor(seq, dtype=dtype)
            return out

        tensors = {
            "student_ids": padded("student"),
            "student_len": torch.tensor([len(slot["student"]) for slot in slots]),
            "prompt_len": torch.tensor([slot["prompt_len"] for slot in slots]),
            "weight": torch.tensor([float(slot.get("weight", 1.0)) for slot in slots]),
            "reverse": torch.tensor([bool(slot.get("reverse", True)) for slot in slots]),
        }
        if loss != "ce":
            tensors.update({"teacher_ids": padded("teacher"), "teacher_mask": padded("teacher_mask", torch.bool),
                            "teacher_len": torch.tensor([len(slot["teacher"]) for slot in slots])})
        batch = DataProto.from_single_dict(tensors)
        batch.meta_info = {"loss": loss, "rows": len(rows)}
        metrics = self.workers.train_step(batch).meta_info["metrics"]

        def values(key: str) -> list:
            value = metrics[key]
            return value if isinstance(value, list) else [value]

        return {"trained_rows": len(rows), "loss": sum(values("loss_sum")) / sum(values("rows")),
                "trained_tokens": int(sum(values("tokens"))), "grad_norm": values("grad_norm")[0],
                "lr": values("lr")[0], "skipped_update": bool(values("skipped")[0])}

    def distill(self, rows: list[dict], rollouts: list[Rollout], step: int, branch: str | None = None) -> dict:
        """Reflect (if the context needs it) and update on `rollouts`; return the step's metrics."""
        if not rows:
            return {"trained_rows": 0}
        t0 = time.time()
        reflections = [None] * len(rows)
        if self.args.context != "conciseness":
            with self.engine():
                reflections = self.reflect(rows, rollouts)
        t1 = time.time()
        built = [self.distill_row(row, rollout, None if r is None else r["memo"])
                 for row, rollout, r in zip(rows, rollouts, reflections)]
        metrics = self.update(built, self.args.loss)
        metrics.update({"reinjections": sum(b["reinjections"] for b in built),
                        "time_reflection_s": round(t1 - t0, 1), "time_update_s": round(time.time() - t1, 1)})
        done = [r for r in reflections if r is not None]
        if done:
            metrics.update({"reflection_tokens": mean([r["tokens"] for r in done]),
                            "reflections_continued": sum(r["continued"] for r in done),
                            "memo_chars": mean([len(r["memo"]) for r in done])})
        for row, rollout, r, b in list(zip(rows, rollouts, reflections, built))[:2]:
            write_jsonl(self.out / "samples.jsonl", {
                "step": step, "branch": branch, "index": row["index"], "answer": row["answer"],
                "outcome": outcome(rollout.correct, rollout.finished), "rollout": rollout.text,
                "reflection_request": None if r is None else r["request"], "memo": None if r is None else r["memo"],
                "teacher_request": teacher_request(self.args.context, row["problem"], None if r is None else r["memo"]),
                "reinjections": b["reinjections"]})
        return metrics

    # -- evaluation ----------------------------------------------------------

    def evaluate(self, step: int, branch: str | None = None) -> list[dict]:
        n = self.args.eval_samples
        jobs = [(name, row, k) for name in sorted(self.benchmarks, key=lambda b: len(self.benchmarks[b]))
                for row in self.benchmarks[name] for k in range(n)]
        prompts = {}
        for name, row, _ in jobs:
            prompts.setdefault((name, row["index"]), self.student_prompt(row))

        def score(i: int, ids: list[int]) -> dict:
            name, row, k = jobs[i]
            text = self.decode(ids)
            correct, prediction = data.check_answer(text, row["answer"], row["data_source"], row["extra_info"],
                                                    tail=data.SCORED_TAIL)
            return {"benchmark": name, "index": row["index"], "sample": k, "correct": correct,
                    "prediction": prediction, "answer": row["answer"], "tokens": len(ids),
                    "finished": self.finished(ids), "response": text}

        t0 = time.time()
        with self.engine():
            records = self.generate([prompts[(name, row["index"])] for name, row, _ in jobs],
                                    self.args.eval_max_tokens, EVAL_TEMPERATURE, score)
        folder = self.out / "eval" / (branch or "") / f"step_{step:04d}"
        summaries = []
        for name in self.benchmarks:
            subset = [r for r in records if r["benchmark"] == name]
            path = folder / f"{name}.jsonl"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in subset), encoding="utf-8")
            summary = {"step": step, "branch": branch, "benchmark": name, "accuracy": mean([r["correct"] for r in subset]),
                       "mean_tokens": mean([r["tokens"] for r in subset]),
                       "truncated": sum(not r["finished"] for r in subset), "problems": len(self.benchmarks[name]),
                       "samples": n}
            write_jsonl(self.out / "eval.jsonl", summary)
            summaries.append(summary)
            print(f"[eval] step {step}{' ' + branch if branch else ''} {name}: accuracy "
                  f"{100 * summary['accuracy']:.1f}%, {summary['mean_tokens']:.0f} tokens", flush=True)
        print(f"[eval] step {step} done in {time.time() - t0:.0f}s", flush=True)
        return summaries

    def is_eval_step(self, step: int) -> bool:
        return step == self.args.steps or (self.args.eval_every > 0 and step % self.args.eval_every == 0)

    # -- runs ----------------------------------------------------------------

    def log(self, record: dict) -> None:
        write_jsonl(self.out / "metrics.jsonl", record)
        shown = {k: (round(v, 4) if isinstance(v, float) else v) for k, v in record.items()
                 if k in ("step", "branch", "accuracy", "truncated", "trained_rows", "loss", "grad_norm",
                          "mean_rollout_tokens", "time_s")}
        print(f"[train] {shown}", flush=True)

    def order(self, epoch: int) -> list[int]:
        return random.Random(f"{self.args.seed}:{epoch}").sample(range(len(self.train)), len(self.train))

    def batch_rows(self, step: int) -> list[dict]:
        size = self.args.batch_size
        rows = []
        for k in range((step - 1) * size, step * size):
            epoch, position = divmod(k, len(self.train))
            rows.append(self.train[self.order(epoch)[position]])
        return rows

    def run(self) -> None:
        if not self.args.skip_initial_eval:
            self.evaluate(0)
        for step in range(1, self.args.steps + 1):
            t0 = time.time()
            rows = self.batch_rows(step)
            with self.engine():
                rollouts = self.sample(rows)
            record = {"step": step, **rollout_stats(rollouts), "time_rollout_s": round(time.time() - t0, 1)}
            if self.method == "rft":
                record.update(self.rft_update(rollouts))
            else:
                keep = [i for i, r in enumerate(rollouts) if gate(self.args.gating, r)]
                record["gated_rows"] = len(keep)
                record.update(self.distill([rows[i] for i in keep], [rollouts[i] for i in keep], step))
            record["time_s"] = round(time.time() - t0, 1)
            self.log(record)
            if self.is_eval_step(step):
                self.evaluate(step)
        if self.args.save_model:
            self.workers.save_checkpoint(str(self.out / "model"), None, self.args.steps, None)

    def rft_update(self, rollouts: list[Rollout]) -> dict:
        correct = [i for i, r in enumerate(rollouts) if r.correct]
        if self.args.selection == "shortest_half":
            kept = shortest_half(correct, [len(r.ids) for r in rollouts])
        else:
            kept = correct
        t0 = time.time()
        rows = [{"student": rollouts[i].prompt + rollouts[i].ids, "prompt_len": len(rollouts[i].prompt)} for i in kept]
        metrics = self.update(rows, "ce")
        metrics.update({"kept_rows": len(kept), "kept_mean_tokens": mean([len(rollouts[i].ids) for i in kept]),
                        "time_update_s": round(time.time() - t0, 1)})
        return metrics

    def run_lockstep(self) -> None:
        branches = ("correct_only", "incorrect_only")
        self.save_branch("initial")
        state = {name: "initial" for name in branches}
        if not self.args.skip_initial_eval:
            self.evaluate(0)
        stream = self.candidates()
        for step in range(1, self.args.steps + 1):
            t0 = time.time()
            matched, record = self.match(stream, state)
            record["time_matching_s"] = round(time.time() - t0, 1)
            write_jsonl(self.out / "matched.jsonl", {"step": step, **record, "prompts": [
                {"index": m["row"]["index"], **{name: {"tokens": len(m[name].ids), "finished": m[name].finished,
                                                       "prediction": m[name].prediction} for name in branches}}
                for m in matched]})
            for name in sorted(branches, key=lambda b: state[b] != self.active):
                t1 = time.time()
                self.activate(state[name])
                rollouts = [m[name] for m in matched]
                metrics = {"step": step, "branch": name, **record, **rollout_stats(rollouts)}
                metrics.update(self.distill([m["row"] for m in matched], rollouts, step, name))
                self.save_branch(name)
                state[name] = name
                metrics["time_s"] = round(time.time() - t1, 1)
                self.log(metrics)
            if self.is_eval_step(step):
                for name in sorted(branches, key=lambda b: state[b] != self.active):
                    self.activate(state[name])
                    self.evaluate(step, name)
        if self.args.save_model:
            for name in branches:
                self.activate(state[name])
                self.workers.save_checkpoint(str(self.out / f"model_{name}"), None, self.args.steps, None)

    def candidates(self):
        epoch = 0
        while True:
            for i in self.order(epoch):
                yield self.train[i]
            epoch += 1

    def match(self, stream, state: dict) -> tuple[list[dict], dict]:
        """Prompts on which both branches have a usable rollout, with the selected rollouts."""
        k, target = self.args.rollouts_per_prompt, self.args.matched_prompts
        matched, candidates = [], 0
        for batch_index in range(1, self.args.max_candidate_batches + 1):
            rows = [next(stream) for _ in range(self.args.candidate_batch_size)]
            candidates += len(rows)
            groups = {}
            for name in sorted(state, key=lambda b: state[b] != self.active):
                self.activate(state[name])
                with self.engine():
                    rollouts = self.sample(rows, per_prompt=k)
                groups[name] = [rollouts[i * k:(i + 1) * k] for i in range(len(rows))]
            for i, row in enumerate(rows):
                right = pick_correct(groups["correct_only"][i])
                wrong = pick_incorrect(groups["incorrect_only"][i])
                if right is not None and wrong is not None and len(matched) < target:
                    matched.append({"row": row, "correct_only": right, "incorrect_only": wrong})
            if len(matched) >= target:
                return matched, {"candidate_prompts": candidates, "candidate_batches": batch_index,
                                 "joint_yield": target / candidates}
        raise RuntimeError(f"only {len(matched)}/{target} prompts matched after {candidates} candidates")


def gate(gating: str, rollout: Rollout) -> bool:
    return gating == "all" or (gating == "correct") == rollout.correct


def pick_correct(group: list[Rollout]) -> Rollout | None:
    return next((r for r in group if r.correct), None)


def pick_incorrect(group: list[Rollout]) -> Rollout | None:
    """The first incorrect rollout that finished, else the first incorrect one."""
    return next((r for r in group if not r.correct and r.finished), None) or next(
        (r for r in group if not r.correct), None)


def rollout_stats(rollouts: list[Rollout]) -> dict:
    return {"rollouts": len(rollouts), "correct": sum(r.correct for r in rollouts),
            "accuracy": mean([r.correct for r in rollouts]), "truncated": sum(not r.finished for r in rollouts),
            "mean_rollout_tokens": mean([len(r.ids) for r in rollouts])}


