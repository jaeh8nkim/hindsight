#!/usr/bin/env python3
"""On-policy self-distillation (OPSD) with a hindsight-conditioned self-teacher.

    python opsd.py --model Qwen/Qwen3-8B --revision <rev> --data data --out D [options]
    python opsd.py --model Qwen/Qwen3-8B --revision <rev> --data data --out D --lockstep --steps 25

Each step samples one rollout per training prompt from the current student (32 prompts,
temperature 1.0, top-p 0.95, up to 8,192 new tokens). The self-teacher is the frozen initial model.
It reads the same rollout after a privileged context, and the student is trained toward the
teacher's full next-token distribution at every rollout token. The per-token divergence is
averaged over each rollout's tokens and then over rollouts. Rollouts are used exactly as sampled:
a rollout cut off by the token budget ends abruptly, without an end-of-sequence token.

Teacher contexts (--context):
  reflection_from_gt    the student is told whether its rollout was correct and the ground-truth
                        answer, and writes a memo; the teacher reads the memo (default)
  conciseness           a fixed instruction to solve concisely; no reflection
  reflection_from_demo  as reflection_from_gt, with an expert solution shown during the reflection
  do_dont               a two-line DO / DON'T note written against an expert solution
  four_line             a four-part, answer-free reflection written against an expert solution
  resolve_from_demo     the student re-solves the problem with an expert solution in view; the
                        teacher reads that solution
The four demo-based contexts need expert demonstrations (`python data.py demos`).

The reflection is generated by the current student with up to 6,144 new tokens. If it is cut off,
generation continues for up to 2,048 more tokens, after closing the thinking block if it is still
open. The memo is the text after the last </think>.

--gating trains on all rollouts, only correct ones, or only incorrect ones. --loss is reverse KL
(default), forward KL, JSD (beta 0.5), or split (reverse KL on correct rollouts, forward KL on the
rest). --reinjection repeats the privileged context inside the teacher's copy of the rollout,
"Actually, I recall: {context}. Continuing from this.", near every 2,048 rollout tokens of thinking
(moved back to the nearest sentence end); the student's input is unchanged.

--lockstep trains a correct-only and an incorrect-only branch from the same start on the same
prompts. Each step streams candidate batches of 32 prompts; each branch samples 4 rollouts per
prompt. A prompt is kept when the correct-only branch has a correct rollout and the incorrect-only
branch has an incorrect one (preferring one that finished), until 16 prompts are matched. Each
branch then reflects on and trains on its own rollouts.

Evaluation runs at step 0, every --eval-every steps, and after the last step: 8 samples per
problem at temperature 0.6, top-p 0.95, up to 30,000 new tokens.
"""

