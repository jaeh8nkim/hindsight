class HindsightWorker(AsyncActorRolloutRefWorker):
    """verl's actor/rollout/reference worker plus the distillation and RFT update and branch snapshots.

    The reference model (loaded from the initial weights and never updated) is the self-teacher.
    """

    @register(dispatch_mode=make_nd_compute_dataproto_dispatch_fn(mesh_name="actor"))
    def train_step(self, batch: DataProto) -> DataProto:
        if self._is_offload_param:
            load_fsdp_model_to_gpu(self.actor_module_fsdp)
        if self._is_offload_optimizer:
            load_fsdp_optimizer(optimizer=self.actor_optimizer, device_id=get_device_id())
        with self.ulysses_sharding_manager:
            metrics = self._train_rows(batch.to("cpu"))
        metrics["lr"] = float(self.actor_lr_scheduler.get_last_lr()[0])
        self.actor_lr_scheduler.step()
        if self._is_offload_param:
            offload_fsdp_model_to_cpu(self.actor_module_fsdp)
        if self._is_offload_optimizer:
            offload_fsdp_optimizer(optimizer=self.actor_optimizer)
        aggressive_empty_cache(force_sync=True)
        return DataProto(meta_info={"metrics": metrics})

    def _train_rows(self, batch: DataProto) -> dict:
        """One optimizer step over this rank's rows, one sequence at a time.

        Each row's loss is the mean over its rollout tokens. Rows are weighted so that, after FSDP
        averages gradients over ranks, the step minimizes the mean row loss over the real rows of the
        global batch; padding rows (weight 0) only keep the ranks' collectives in step.
        """
        kind = batch.meta_info["loss"]
        scale = torch.distributed.get_world_size() / float(batch.meta_info["rows"])
        tensors = batch.batch
        device = torch.device(get_device_name(), get_device_id())
        self.actor_module_fsdp.train()
        if kind != "ce":
            self.ref_module_fsdp.eval()
        self.actor_optimizer.zero_grad()
        loss_sum = rows = tokens = 0.0
        for i in range(len(batch)):
            weight = float(tensors["weight"][i])
            length, prompt = int(tensors["student_len"][i]), int(tensors["prompt_len"][i])
            ids = tensors["student_ids"][i, :length].to(device)
            teacher = None
            if kind != "ce":
                t_len = int(tensors["teacher_len"][i])
                t_ids = tensors["teacher_ids"][i, :t_len].to(device)
                t_keep = tensors["teacher_mask"][i, :t_len].nonzero().squeeze(-1).to(device) - 1
                with torch.no_grad():
                    teacher = response_logits(self.ref_module_fsdp, t_ids, t_keep)
            student = response_logits(self.actor_module_fsdp, ids, torch.arange(prompt - 1, length - 1, device=device))
            n = student.shape[0]
            if teacher is not None and teacher.shape[0] != n:
                raise RuntimeError(f"teacher has {teacher.shape[0]} rollout positions, student {n}")
            row_kind = kind
            if kind == "split":
                row_kind = "reverse_kl" if bool(tensors["reverse"][i]) else "forward_kl"
            total = backward_in_chunks(student, teacher, ids[prompt:], row_kind, weight * scale / n)
            loss_sum += weight * total / n
            rows += weight
            tokens += weight * n
            del student, teacher

        if isinstance(self.actor_module_fsdp, FSDP):
            grad_norm = self.actor_module_fsdp.clip_grad_norm_(max_norm=self.config.actor.grad_clip)
        else:
            from verl.utils.fsdp_utils import fsdp2_clip_grad_norm_

            grad_norm = fsdp2_clip_grad_norm_(self.actor_module_fsdp.parameters(), max_norm=self.config.actor.grad_clip)
        if hasattr(grad_norm, "full_tensor"):
            grad_norm = grad_norm.full_tensor()
        finite = bool(torch.isfinite(grad_norm))
        if finite:
            self.actor_optimizer.step()
        self.actor_optimizer.zero_grad()
        return {"loss_sum": loss_sum, "rows": rows, "tokens": tokens, "grad_norm": float(grad_norm),
                "skipped": int(not finite)}

    @register(dispatch_mode=Dispatch.ONE_TO_ALL)
    def save_branch(self, path: str, rank: int) -> None:
        """Save this rank's actor parameters, optimizer, and scheduler (called for one rank at a time)."""
        if torch.distributed.get_rank() != rank:
            return
        state = {
            "params": [p.detach().cpu() for p in self.actor_module_fsdp.parameters()],
            "buffers": [b.detach().cpu() for b in self.actor_module_fsdp.buffers()],
            "optimizer": self.actor_optimizer.state_dict(),
            "lr_scheduler": self.actor_lr_scheduler.state_dict(),
        }
        target = Path(path) / f"rank_{rank}.pt"
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp = target.with_suffix(".tmp")
        torch.save(state, tmp)
        os.replace(tmp, target)
        del state
        aggressive_empty_cache()

    @register(dispatch_mode=Dispatch.ONE_TO_ALL)
    def load_branch(self, path: str, rank: int) -> None:
        if torch.distributed.get_rank() != rank:
            return
        state = torch.load(Path(path) / f"rank_{rank}.pt", map_location="cpu", weights_only=False, mmap=True)
        with torch.no_grad():
            for live, saved in zip(self.actor_module_fsdp.parameters(), state["params"], strict=True):
                live.copy_(saved)
            for live, saved in zip(self.actor_module_fsdp.buffers(), state["buffers"], strict=True):
                live.copy_(saved)
        self.actor_optimizer.load_state_dict(state["optimizer"])
        device = torch.device("cpu") if self._is_offload_optimizer else torch.device(get_device_name(), get_device_id())
        for values in self.actor_optimizer.state.values():
            for key, value in list(values.items()):
                if torch.is_tensor(value):
                    values[key] = value.to(device)
        self.actor_lr_scheduler.load_state_dict(state["lr_scheduler"])
        del state
        aggressive_empty_cache()


